"""Unit tests for the Sense 0.1.0 models and validator (KOS-SDK-003 AC-005). Standard library only.

Examples are authored here from the prose contract (SENSE_CONTRACT.md); they are not generated by the SDK validator.
Cross-validation against the pinned upstream fixtures and reference validator is stage d (AC-008).
"""
import copy
import dataclasses
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import kritva_sdk.sense as sense  # noqa: E402
from kritva_sdk.errors import ContractError, UnsupportedContractVersion  # noqa: E402
from kritva_sdk.sense import Measurement, SenseSample, Timestamp, parse_sample, validate_sample  # noqa: E402

BASES = {
    "imu": {n: {"value": 0.25, "unit": u} for n, u in (("accel_x", "m/s^2"), ("accel_y", "m/s^2"), ("accel_z", "m/s^2"),
                                                       ("gyro_x", "rad/s"), ("gyro_y", "rad/s"), ("gyro_z", "rad/s"))},
    "range": {"distance": {"value": 1.5, "unit": "m"}},
    "encoder": {"position": {"value": 3, "unit": "rad"}},
    "temperature": {"temperature": {"value": 293.15, "unit": "K"}},
}


def sample(kind="range", **over):
    s = {"contract_version": "0.1.0", "sensor_id": "front.range_1", "kind": kind, "sequence": 7,
         "timestamp": {"clock": "monotonic", "unit": "ns", "value": 1000}, "frame_id": "base", "validity": "VALID",
         "measurements": copy.deepcopy(BASES.get(kind if isinstance(kind, str) else "", BASES["range"]))}
    s.update(over)
    return s


def codes(payload):
    return [(v.code, v.path) for v in validate_sample(payload)]


class ValidSamples(unittest.TestCase):
    def test_every_kind_validates_and_round_trips(self):
        for kind in BASES:
            with self.subTest(kind=kind):
                payload = sample(kind)
                self.assertEqual(validate_sample(payload), ())
                parsed = parse_sample(payload)
                self.assertEqual(parsed.to_dict(), payload)
                self.assertEqual(parse_sample(parsed.to_dict()), parsed)

    def test_round_trip_preserves_int_and_float_and_key_content(self):
        payload = sample("encoder")
        out = parse_sample(payload).to_dict()
        self.assertIs(type(out["measurements"]["position"]["value"]), int)
        out2 = parse_sample(sample("range")).to_dict()
        self.assertIs(type(out2["measurements"]["distance"]["value"]), float)

    def test_json_serialisation_is_strict(self):
        text = json.dumps(parse_sample(sample("imu")).to_dict(), allow_nan=False)
        self.assertEqual(parse_sample(json.loads(text)).kind, "imu")

    def test_utc_clock_and_all_frames(self):
        for frame in ("world", "base", "sensor"):
            p = sample(frame_id=frame, timestamp={"clock": "utc", "unit": "ns", "value": 0})
            self.assertEqual(validate_sample(p), (), frame)

    def test_sensor_id_forms(self):
        for sid in ("a", "imu0", "front.range_1", "a.b.c.d", "a" + "b" * 31):
            self.assertEqual(validate_sample(sample(sensor_id=sid)), (), sid)
        for sid in ("", "A", "1a", "a.", ".a", "a..b", "a.b.c.d.e", "a" + "b" * 32, "a-b", "a b", "a." + "b" * 33):
            self.assertEqual(codes(sample(sensor_id=sid)), [("INVALID_SENSOR_ID", "sensor_id")], sid)


class ValidityCoupling(unittest.TestCase):
    def test_missing_requires_error_code_and_empty_measurements(self):
        ok = sample(validity="MISSING", error_code="MISSING_DATA", measurements={})
        self.assertEqual(validate_sample(ok), ())
        parsed = parse_sample(ok)
        self.assertEqual(dict(parsed.measurements), {})
        self.assertEqual(parsed.to_dict(), ok)
        self.assertEqual(codes(sample(validity="MISSING", error_code="MISSING_DATA")),
                         [("MALFORMED_FIELD", "measurements")])
        self.assertEqual(codes(sample(validity="MISSING", measurements={})), [("MISSING_FIELD", "error_code")])

    def test_stale_and_invalid_keep_last_known_measurements(self):
        for state, code in (("STALE", "STALE_DATA"), ("INVALID", "INVALID_DATA")):
            with self.subTest(state=state):
                payload = sample("imu", validity=state, error_code=code)
                parsed = parse_sample(payload)
                self.assertEqual(len(parsed.measurements), 6)
                self.assertEqual(parsed.error_code, code)
                self.assertEqual(parsed.to_dict(), payload)
                gone = sample("imu", validity=state, error_code=code, measurements={})
                self.assertTrue(codes(gone))  # measurements are required for non-MISSING states

    def test_valid_forbids_error_code(self):
        self.assertEqual(codes(sample(error_code="STALE_DATA")), [("MALFORMED_FIELD", "error_code")])

    def test_error_code_presence_is_preserved_exactly(self):
        self.assertNotIn("error_code", parse_sample(sample()).to_dict())
        self.assertIsNone(parse_sample(sample()).error_code)
        self.assertIn("error_code", parse_sample(sample(validity="STALE", error_code="STALE_DATA")).to_dict())
        self.assertEqual(codes(sample(validity="STALE", error_code=None)), [("MALFORMED_FIELD", "error_code")])

    def test_unknown_error_code_and_validity(self):
        self.assertEqual(codes(sample(validity="STALE", error_code="NOPE")), [("MALFORMED_FIELD", "error_code")])
        for v in ("valid", "OK", "", None, 1, [], {}):
            self.assertEqual(codes(sample(validity=v)), [("INVALID_VALIDITY", "validity")], repr(v))

    def test_all_defined_error_codes_accepted_when_not_valid(self):
        for code in sense.ERROR_CODES:
            self.assertEqual(validate_sample(sample(validity="INVALID", error_code=code)), (), code)


class FieldRules(unittest.TestCase):
    def test_missing_fields(self):
        for name in sense._REQUIRED:
            p = sample()
            del p[name]
            self.assertIn(("MISSING_FIELD", name), codes(p), name)

    def test_unknown_fields_rejected_at_every_level(self):
        p = sample(); p["extra"] = 1
        self.assertEqual(codes(p), [("UNKNOWN_FIELD", "extra")])
        p = sample(); p["timestamp"]["zone"] = "x"
        self.assertEqual(codes(p), [("UNKNOWN_FIELD", "timestamp.zone")])
        p = sample(); p["measurements"]["distance"]["extra"] = 1
        self.assertEqual(codes(p), [("UNKNOWN_FIELD", "measurements.distance.extra")])
        p = sample(); p["measurements"]["velocity"] = {"value": 1, "unit": "m"}
        self.assertEqual(codes(p), [("UNKNOWN_FIELD", "measurements.velocity")])

    def test_missing_measurement_of_kind(self):
        p = sample("imu"); del p["measurements"]["gyro_z"]
        self.assertEqual(codes(p), [("MISSING_FIELD", "measurements.gyro_z")])

    def test_units_are_exact_and_never_converted(self):
        for bad in ("km", "mm", "M", "", None, 1):
            p = sample(); p["measurements"]["distance"]["unit"] = bad
            self.assertEqual(codes(p), [("INVALID_UNIT", "measurements.distance.unit")], repr(bad))
        p = sample("temperature"); p["measurements"]["temperature"]["unit"] = "C"
        self.assertEqual(codes(p), [("INVALID_UNIT", "measurements.temperature.unit")])
        self.assertEqual(parse_sample(sample("temperature")).measurements["temperature"].unit, "K")

    def test_timestamp_rules(self):
        cases = {
            "not an object": ("timestamp", "x", [("INVALID_TIMESTAMP", "timestamp")]),
            "bad clock": ("clock", "wall", [("INVALID_TIMESTAMP", "timestamp.clock")]),
            "bad unit": ("unit", "us", [("INVALID_TIMESTAMP", "timestamp.unit")]),
            "negative": ("value", -1, [("INVALID_TIMESTAMP", "timestamp.value")]),
            "float": ("value", 1.0, [("INVALID_TIMESTAMP", "timestamp.value")]),
            "bool": ("value", True, [("INVALID_TIMESTAMP", "timestamp.value")]),
        }
        for label, (field, value, expected) in cases.items():
            with self.subTest(label):
                p = sample()
                if field == "timestamp":
                    p["timestamp"] = value
                else:
                    p["timestamp"][field] = value
                self.assertEqual(codes(p), expected)
        p = sample(); del p["timestamp"]["unit"]
        self.assertEqual(codes(p), [("INVALID_TIMESTAMP", "timestamp.unit")])

    def test_sequence_rules(self):
        self.assertEqual(validate_sample(sample(sequence=0)), ())
        for bad in (-1, 1.0, True, "1", None):
            self.assertEqual(codes(sample(sequence=bad)), [("MALFORMED_FIELD", "sequence")], repr(bad))

    def test_frame_rules(self):
        self.assertEqual(codes(sample(frame_id="map")), [("UNKNOWN_FRAME", "frame_id")])
        self.assertEqual(codes(sample(frame_id=1)), [("MALFORMED_FIELD", "frame_id")])

    def test_kind_rules(self):
        self.assertEqual(codes(sample(kind="lidar")), [("MALFORMED_FIELD", "kind")])
        self.assertEqual(codes(sample(kind=3)), [("MALFORMED_FIELD", "kind")])

    def test_booleans_and_strings_are_not_numbers(self):
        for bad in (True, False, "1.0", None, [1]):
            p = sample(); p["measurements"]["distance"]["value"] = bad
            self.assertEqual(codes(p), [("MALFORMED_FIELD", "measurements.distance.value")], repr(bad))

    def test_non_finite_values_are_non_finite_not_generic(self):
        for bad in (float("nan"), float("inf"), float("-inf")):
            p = sample(); p["measurements"]["distance"]["value"] = bad
            self.assertEqual(codes(p), [("NON_FINITE_VALUE", "measurements.distance.value")], repr(bad))
            with self.assertRaises(ContractError) as cm:
                parse_sample(p)
            self.assertEqual(cm.exception.code, "NON_FINITE_VALUE")

    def test_measurement_shape(self):
        p = sample(); p["measurements"]["distance"] = 1.0
        self.assertEqual(codes(p), [("MALFORMED_FIELD", "measurements.distance")])
        p = sample(); p["measurements"] = []
        self.assertEqual(codes(p), [("MALFORMED_FIELD", "measurements")])
        p = sample(); del p["measurements"]["distance"]["unit"]
        self.assertEqual(codes(p), [("MISSING_FIELD", "measurements.distance.unit")])

    def test_non_object_samples_never_raise(self):
        for bad in (None, 1, "x", [], [1], 1.5, True):
            self.assertEqual(codes(bad), [("MALFORMED_FIELD", "$")], repr(bad))
            with self.assertRaises(ContractError):
                parse_sample(bad)

    def test_unhashable_and_odd_values_never_raise(self):
        for odd in ([], {}, [1, 2], {"a": 1}, object()):
            for field in ("validity", "kind", "frame_id", "sensor_id", "sequence", "error_code", "contract_version",
                          "timestamp", "measurements"):
                validate_sample(sample(**{field: odd}))


class VersionHandling(unittest.TestCase):
    def test_unsupported_version_fails_early_in_parse(self):
        p = sample(contract_version="0.2.0", kind="bogus", frame_id="map")
        with self.assertRaises(UnsupportedContractVersion) as cm:
            parse_sample(p)
        self.assertEqual(cm.exception.code, "UNSUPPORTED_CONTRACT_VERSION")
        self.assertEqual(cm.exception.path, "contract_version")
        self.assertEqual(len(cm.exception.violations), 1)

    def test_validate_reports_the_version_alongside_other_violations(self):
        got = codes(sample(contract_version="0.2.0", frame_id="map"))
        self.assertIn(("UNSUPPORTED_CONTRACT_VERSION", "contract_version"), got)
        self.assertIn(("UNKNOWN_FRAME", "frame_id"), got)

    def test_wrong_type_version_is_malformed(self):
        for bad in (None, 1, 0.1, ["0.1.0"]):
            with self.assertRaises(ContractError) as cm:
                parse_sample(sample(contract_version=bad))
            self.assertEqual(cm.exception.code, "MALFORMED_FIELD")
            self.assertNotIsInstance(cm.exception, UnsupportedContractVersion)

    def test_version_agrees_with_compat_declaration(self):
        from kritva_sdk import supported_contracts
        self.assertEqual((sense.SENSE_CONTRACT_VERSION,), supported_contracts()["sense"])


class Ordering(unittest.TestCase):
    def test_multiple_violations_are_sorted_and_stable(self):
        p = sample(frame_id="map", sequence=-1, sensor_id="A", extra=1)
        got = validate_sample(p)
        self.assertEqual(list(got), sorted(got))
        self.assertEqual(got, validate_sample(copy.deepcopy(p)))
        self.assertGreater(len(got), 3)

    def test_parse_error_carries_all_violations_first_one_as_code(self):
        with self.assertRaises(ContractError) as cm:
            parse_sample(sample(frame_id="map", sequence=-1))
        self.assertEqual(cm.exception.violations, validate_sample(sample(frame_id="map", sequence=-1)))
        self.assertEqual((cm.exception.path, cm.exception.code), ("frame_id", "UNKNOWN_FRAME"))


class Models(unittest.TestCase):
    def test_models_are_frozen(self):
        s = parse_sample(sample())
        with self.assertRaises(dataclasses.FrozenInstanceError):
            s.sequence = 1  # type: ignore[misc]
        with self.assertRaises(dataclasses.FrozenInstanceError):
            s.timestamp.value = 1  # type: ignore[misc]
        with self.assertRaises(dataclasses.FrozenInstanceError):
            s.measurements["distance"].unit = "km"  # type: ignore[misc]
        with self.assertRaises(TypeError):
            s.measurements["extra"] = Measurement(1, "m")  # type: ignore[index]

    def test_parsed_sample_is_independent_of_the_input_dict(self):
        p = sample()
        s = parse_sample(p)
        p["measurements"]["distance"]["value"] = 99.0
        p["timestamp"]["value"] = 5
        self.assertEqual(s.measurements["distance"].value, 1.5)
        self.assertEqual(s.timestamp.value, 1000)

    def test_to_dict_is_a_fresh_copy(self):
        s = parse_sample(sample())
        d = s.to_dict()
        d["measurements"]["distance"]["value"] = 0.0
        self.assertEqual(s.to_dict()["measurements"]["distance"]["value"], 1.5)

    def test_equality_and_hash(self):
        a, b = parse_sample(sample()), parse_sample(sample())
        self.assertEqual(a, b)
        self.assertEqual(hash(a), hash(b))
        self.assertNotEqual(a, parse_sample(sample(sequence=8)))
        self.assertEqual(len({a, b}), 1)

    def test_direct_construction_validates(self):
        ts = Timestamp(clock="monotonic", value=1)
        ok = SenseSample("0.1.0", "s", "range", 0, ts, "base", "VALID", {"distance": Measurement(1.0, "m")})
        self.assertEqual(ok.to_dict()["measurements"]["distance"], {"value": 1.0, "unit": "m"})
        with self.assertRaises(ContractError) as cm:
            SenseSample("0.1.0", "s", "range", 0, ts, "base", "VALID", {"distance": Measurement(1.0, "km")})
        self.assertEqual(cm.exception.code, "INVALID_UNIT")
        with self.assertRaises(ContractError):
            SenseSample("0.1.0", "s", "range", 0, ts, "base", "STALE", {"distance": Measurement(1.0, "m")})
        with self.assertRaises(ContractError):
            Timestamp(clock="wall", value=1)
        with self.assertRaises(ContractError):
            Timestamp(clock="utc", value=-1)

    def test_from_dict_is_parse(self):
        self.assertEqual(SenseSample.from_dict(sample()), parse_sample(sample()))

    def test_constants_are_immutable(self):
        with self.assertRaises(TypeError):
            sense.KINDS["lidar"] = {}  # type: ignore[index]
        with self.assertRaises(TypeError):
            sense.KINDS["range"]["distance"] = "km"  # type: ignore[index]


